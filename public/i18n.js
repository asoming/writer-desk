  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT),nodes=[];let node;
  while((node=walker.nextNode()))nodes.push(node);
  for(const text of nodes){if(text.parentElement?.closest('script,style'))continue;const trimmed=text.textContent.trim();if(englishMessages[trimmed])text.textContent=text.textContent.replace(trimmed,T(trimmed));}
  for(const element of document.querySelectorAll('[aria-label],[placeholder],[title],meta[name="description"]')){
    for(const attr of ['aria-label','placeholder','title','content']){const value=element.getAttribute(attr);if(value&&englishMessages[value])element.setAttribute(attr,T(value));}
  }
  document.title=T('作家工作台 · 本地写作工作室');
